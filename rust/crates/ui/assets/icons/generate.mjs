// Regenerates the icon assets from the web UI's sources of truth:
//   frontend/src/lib/icons.ts            → app/<name>.svg + src/icon_name.rs
//   frontend/src/lib/lucide-icons.ts     → lucide/<name>.svg + lucide.json (catalog, aliases, suggested)
//   frontend/src/components/ProviderIcon.svelte → provider/<slug>.svg
//
// Run from the repo root after `cd frontend && pnpm install`:
//   node --experimental-strip-types rust/crates/ui/assets/icons/generate.mjs
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = join(here, '..', '..', '..', '..', '..')
const lib = join(repo, 'frontend', 'src', 'lib')

const { icons } = await import(pathToFileURL(join(lib, 'icons.ts')).href)
const { lucideIcons, lucideSuggested, lucideInnerHtml } = await import(pathToFileURL(join(lib, 'lucide-icons.ts')).href)

function fresh(dir) {
  rmSync(dir, { recursive: true, force: true })
  mkdirSync(dir, { recursive: true })
}

// Icon.svelte's <svg>: fill/stroke from `filled`, stroke-width default 2, viewBox default 0 0 24 24.
fresh(join(here, 'app'))
const names = Object.keys(icons)
for (const name of names) {
  const def = icons[name]
  const vb = def.viewBox ?? '0 0 24 24'
  const attrs = def.filled
    ? `fill="currentColor" stroke="none"`
    : `fill="none" stroke="currentColor" stroke-width="${def.strokeWidth ?? 2}" stroke-linecap="round" stroke-linejoin="round"`
  writeFileSync(join(here, 'app', `${name}.svg`), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" ${attrs}>${def.body}</svg>\n`)
}

// LucideIcon.svelte's <svg>.
fresh(join(here, 'lucide'))
for (const entry of lucideIcons) {
  writeFileSync(
    join(here, 'lucide', `${entry.name}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${lucideInnerHtml(entry.name)}</svg>\n`,
  )
}
writeFileSync(
  join(here, 'lucide.json'),
  JSON.stringify({
    icons: lucideIcons.map((e) => ({ name: e.name, aliases: e.aliases })),
    suggested: lucideSuggested.map((e) => e.name),
  }) + '\n',
)

// ProviderIcon.svelte: one <svg> per {#if} branch, last branch is the generic mark.
fresh(join(here, 'provider'))
const provider = readFileSync(join(repo, 'frontend', 'src', 'components', 'ProviderIcon.svelte'), 'utf8')
const svgs = [...provider.matchAll(/<svg([^>]*)>([\s\S]*?)<\/svg>/g)].map((m) => {
  const attrs = m[1].replace(/\s*aria-hidden="true"/, '')
  const body = m[2].replace(/\n\s*/g, ' ').replace(/\s+\/>/g, '/>').trim()
  return `<svg xmlns="http://www.w3.org/2000/svg"${attrs}>${body}</svg>\n`
})
const slugs = ['cursor', 'claude', 'codex', 'ollama', 'generic']
if (svgs.length !== slugs.length) throw new Error(`ProviderIcon.svelte has ${svgs.length} marks, expected ${slugs.length}`)
slugs.forEach((slug, i) => writeFileSync(join(here, 'provider', `${slug}.svg`), svgs[i]))

// IconName enum: one variant per icons.ts key, in source order.
const pascal = (k) => k.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('')
const rs = `// Generated by assets/icons/generate.mjs from frontend/src/lib/icons.ts. Do not edit.

/// A key of the app icon registry (\`IconName\` in \`lib/icons.ts\`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum IconName {
${names.map((n) => `    ${pascal(n)},`).join('\n')}
}

impl IconName {
    pub const ALL: [IconName; ${names.length}] = [
${names.map((n) => `        IconName::${pascal(n)},`).join('\n')}
    ];

    /// The registry key, e.g. \`"chevron-down"\`.
    pub fn key(self) -> &'static str {
        match self {
${names.map((n) => `            IconName::${pascal(n)} => ${JSON.stringify(n)},`).join('\n')}
        }
    }

    pub fn from_key(key: &str) -> Option<IconName> {
        IconName::ALL.into_iter().find(|i| i.key() == key)
    }
}
`
writeFileSync(join(here, '..', '..', 'src', 'icon_name.rs'), rs)
console.log(`${names.length} app icons, ${lucideIcons.length} lucide icons, ${slugs.length} provider marks`)
