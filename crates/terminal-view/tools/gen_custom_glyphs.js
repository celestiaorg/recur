// Regenerates src/custom_glyph_data.rs from xterm.js's @xterm/addon-webgl custom glyph table.
//
//   node tools/gen_custom_glyphs.js <path to @xterm/addon-webgl/src/customGlyphs> > src/custom_glyph_data.rs
//
// Definitions that are closures over (xp, yp) (the cell aspect ratio) are evaluated at several
// points; every number they produce is linear in xp and yp, recorded as [a, b, c] for
// a + b*xp + c*yp. The script fails if that ever stops holding.
const path = require('path');
const fs = require('fs');
const os = require('os');
const dir = process.argv[2];
const ts = require(require.resolve('typescript', { paths: [dir, path.join(dir, '../../../../..')] }));
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cg-'));
for (const f of ['Types', 'CustomGlyphDefinitions']) {
  const src = fs.readFileSync(path.join(dir, f + '.ts'), 'utf8');
  const out = ts.transpileModule(src, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, preserveConstEnums: true },
  });
  fs.writeFileSync(path.join(tmp, f + '.js'), out.outputText);
}
const defs = require(path.join(tmp, 'CustomGlyphDefinitions.js')).customGlyphDefinitions;

const num = (x) => {
  if (!Number.isFinite(x)) throw new Error('non-finite ' + x);
  const s = String(x);
  return s.includes('.') || s.includes('e') ? s : s + '.0';
};

function tokenize(str) {
  return str.split(' ').map((ins) => ({ cmd: ins[0] ?? '', args: ins.substring(1).split(',') }));
}

function parseArg(s) {
  if (!s) return null;
  const v = parseFloat(s) || parseInt(s);
  return Number.isNaN(v) ? null : v;
}

function instrs(def) {
  if (typeof def === 'string') {
    return tokenize(def).map((t) => ({ cmd: t.cmd, args: t.args.map((a) => { const v = parseArg(a); return v === null ? null : [v, 0, 0]; }), raw: t.args }));
  }
  const at = (x, y) => tokenize(def(x, y));
  const base = at(0, 0), dx = at(1, 0), dy = at(0, 1), probe = at(0.37, 0.61);
  return base.map((t, i) => {
    if (dx[i].cmd !== t.cmd || dy[i].cmd !== t.cmd || probe[i].cmd !== t.cmd) throw new Error('structure varies');
    return {
      cmd: t.cmd,
      raw: t.args,
      args: t.args.map((a, j) => {
        const v0 = parseArg(a);
        if (v0 === null) return null;
        const b = parseArg(dx[i].args[j]) - v0, c = parseArg(dy[i].args[j]) - v0;
        const p = parseArg(probe[i].args[j]);
        if (Math.abs(v0 + 0.37 * b + 0.61 * c - p) > 1e-9) throw new Error('non-linear arg');
        return [v0, b, c];
      }),
    };
  });
}

function rustInstrs(list) {
  return '&[' + list.map((t) => {
    const args = t.args.map((a) => (a === null ? 'None' : `Some([${a.map(num).join(', ')}])`));
    return `I { cmd: b'${t.cmd === "'" ? "\\'" : t.cmd || ' '}', args: &[${args.join(', ')}] }`;
  }).join(', ') + ']';
}

function rustPart(p) {
  let kind;
  switch (p.type) {
    case 0: kind = `K::Octants(&[${p.data.map((b) => `[${[b.x, b.y, b.w, b.h].map(num).join(', ')}]`).join(', ')}])`; break;
    case 1: kind = `K::Pattern(&[${p.data.map((r) => `&[${r.map(num).join(', ')}]`).join(', ')}])`; break;
    case 2: kind = `K::PathFn(${rustInstrs(instrs(p.data))})`; break;
    case 3: kind = `K::Path(${rustInstrs(instrs(typeof p.data === 'function' ? p.data(0, 0) : p.data))})`; break;
    // The negative shape is drawn in the atlas background, transparent in Recur's pane.
    case 4: kind = 'K::PathNegative'; break;
    case 5: kind = `K::Vector { d: ${rustInstrs(instrs(p.data.d))}, stroke: ${p.data.type === 1}, left_padding: ${num(p.data.leftPadding ?? 0)}, right_padding: ${num(p.data.rightPadding ?? 0)} }`; break;
    case 6: kind = `K::Braille(${p.data})`; break;
    default: throw new Error('unknown type ' + p.type);
  }
  const sw = p.strokeWidth === undefined ? 'None' : `Some(${num(p.strokeWidth)})`;
  const clip = p.clipPath ? `Some(${rustInstrs(instrs(p.clipPath))})` : 'None';
  return `P { kind: ${kind}, stroke_width: ${sw}, clip: ${clip}, char_scale: ${p.scaleType === 1} }`;
}

const entries = Object.entries(defs)
  .filter(([, v]) => v)
  .map(([ch, v]) => [ch.codePointAt(0), Array.isArray(v) ? v : [v]])
  .sort((a, b) => a[0] - b[0]);

let out = '';
out += '//! Generated by `tools/gen_custom_glyphs.js` from @xterm/addon-webgl `CustomGlyphDefinitions.ts`.\n';
out += '//! Do not edit by hand.\n\n';
out += '// The numbers are xterm.js literals, not approximations of library constants.\n';
out += '#![allow(clippy::excessive_precision, clippy::approx_constant)]\n\n';
out += 'use crate::custom_glyphs::{I, K, P};\n\n';
out += `pub(crate) static GLYPHS: [(u32, &[P]); ${entries.length}] = [\n`;
for (const [cp, parts] of entries) {
  out += `    (0x${cp.toString(16).toUpperCase()}, &[${parts.map(rustPart).join(', ')}]),\n`;
}
out += '];\n';
process.stdout.write(out);
